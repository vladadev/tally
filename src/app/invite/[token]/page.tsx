"use client";

import React, { useEffect, useState, use } from "react";
import { useRouter } from "next/navigation";
import Link from "next/link";
import { Button } from "@/components/ui/button";
import { Card, CardHeader, CardTitle, CardDescription, CardContent } from "@/components/ui/card";
import { Badge } from "@/components/ui/badge";
import { useToast } from "@/components/ui/toast";
import { Users, UserPlus, LogIn, ArrowRight } from "lucide-react";

interface InviteGroupInfo {
  id: string;
  name: string;
  description?: string | null;
  currency: string;
  ownerName: string;
  memberCount: number;
}

export default function InviteJoinPage({
  params,
}: {
  params: Promise<{ token: string }>;
}) {
  const { token } = use(params);
  const router = useRouter();
  const { success, error } = useToast();

  const [group, setGroup] = useState<InviteGroupInfo | null>(null);
  const [currentUser, setCurrentUser] = useState<{ id: string; name: string } | null>(null);
  const [loading, setLoading] = useState(true);
  const [joining, setJoining] = useState(false);
  const [notFound, setNotFound] = useState(false);

  useEffect(() => {
    // Check session & fetch invite details
    Promise.all([
      fetch("/api/auth/me").then((res) => (res.ok ? res.json() : null)),
      fetch(`/api/invite/${token}`).then((res) => {
        if (!res.ok) throw new Error("Not found");
        return res.json();
      }),
    ])
      .then(([userData, inviteData]) => {
        if (userData?.user) setCurrentUser(userData.user);
        if (inviteData?.group) setGroup(inviteData.group);
      })
      .catch(() => {
        setNotFound(true);
      })
      .finally(() => setLoading(false));
  }, [token]);

  const handleJoin = async () => {
    if (!currentUser) {
      router.push(`/login?from=/invite/${token}`);
      return;
    }

    setJoining(true);
    try {
      const res = await fetch(`/api/invite/${token}`, { method: "POST" });
      const data = await res.json();

      if (!res.ok) {
        error(data.error || "Failed to join group");
        return;
      }

      success(data.message || "Joined group!");
      router.push(`/groups/${data.groupId}`);
    } catch {
      error("Network error joining group");
    } finally {
      setJoining(false);
    }
  };

  if (loading) {
    return (
      <div className="flex-1 flex items-center justify-center p-4">
        <div className="w-full max-w-md h-64 bg-zinc-200 dark:bg-zinc-800 rounded-2xl animate-pulse" />
      </div>
    );
  }

  if (notFound || !group) {
    return (
      <div className="flex-1 flex items-center justify-center p-4">
        <Card className="w-full max-w-md p-8 text-center">
          <div className="mx-auto w-12 h-12 rounded-2xl bg-rose-100 dark:bg-rose-950/60 text-rose-600 dark:text-rose-400 flex items-center justify-center mb-4">
            <Users className="w-6 h-6" />
          </div>
          <CardTitle className="text-xl font-bold">Invite Not Found</CardTitle>
          <CardDescription className="mt-2">
            This invite link is invalid or has been regenerated by the group owner.
          </CardDescription>
          <Link href="/dashboard" className="mt-6 inline-block">
            <Button variant="secondary">Go to Dashboard</Button>
          </Link>
        </Card>
      </div>
    );
  }

  return (
    <div className="flex-1 flex items-center justify-center p-4 py-12">
      <Card className="w-full max-w-md shadow-2xl border-zinc-200/80 dark:border-zinc-800">
        <CardHeader className="text-center pb-4">
          <div className="mx-auto w-14 h-14 rounded-2xl bg-emerald-600/10 dark:bg-emerald-600/20 text-emerald-600 dark:text-emerald-400 flex items-center justify-center mb-3">
            <UserPlus className="w-7 h-7" />
          </div>
          <Badge variant="secondary" className="mx-auto mb-2 text-xs font-mono">
            {group.currency}
          </Badge>
          <CardTitle className="text-2xl font-bold">{group.name}</CardTitle>
          {group.description && (
            <CardDescription className="text-sm mt-1">{group.description}</CardDescription>
          )}
        </CardHeader>

        <CardContent className="space-y-6 pt-2">
          <div className="p-4 rounded-xl bg-zinc-50 dark:bg-zinc-800/50 border border-zinc-200/60 dark:border-zinc-800 text-sm space-y-2">
            <div className="flex justify-between text-zinc-600 dark:text-zinc-400">
              <span>Invited by</span>
              <span className="font-semibold text-zinc-900 dark:text-zinc-100">
                {group.ownerName}
              </span>
            </div>
            <div className="flex justify-between text-zinc-600 dark:text-zinc-400">
              <span>Group members</span>
              <span className="font-semibold text-zinc-900 dark:text-zinc-100">
                {group.memberCount}
              </span>
            </div>
          </div>

          {currentUser ? (
            <div className="space-y-3">
              <p className="text-xs text-center text-zinc-500 dark:text-zinc-400">
                You are signed in as <span className="font-semibold">{currentUser.name}</span>
              </p>
              <Button
                onClick={handleJoin}
                isLoading={joining}
                className="w-full h-11 text-base shadow-md"
              >
                Join {group.name}
                <ArrowRight className="w-4 h-4 ml-2" />
              </Button>
            </div>
          ) : (
            <div className="space-y-3">
              <Button
                onClick={() => router.push(`/login?from=/invite/${token}`)}
                className="w-full h-11 text-base shadow-md"
              >
                <LogIn className="w-4 h-4 mr-2" />
                Sign in to join
              </Button>
              <p className="text-xs text-center text-zinc-500 dark:text-zinc-400">
                Don't have an account?{" "}
                <Link
                  href={`/register?from=/invite/${token}`}
                  className="font-semibold text-emerald-600 dark:text-emerald-400 hover:underline"
                >
                  Create one now
                </Link>
              </p>
            </div>
          )}
        </CardContent>
      </Card>
    </div>
  );
}
